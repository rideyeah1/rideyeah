/**
 * RideYeah · Sync the Travel Hub static export into this repo
 * ----------------------------------------------------------
 * The Travel Hub (rideyeah.com/travel) is a SEPARATE Next.js project that builds
 * to its own `out/`. This is a LOCAL developer tool that rebuilds the hub and
 * copies its `out/` into this repo's tracked `travel-static/` folder. That folder
 * is committed so the Cloudflare build (which runs `scripts/build.mjs` in CI) can
 * drop it into `dist/travel/` with no access to the hub source.
 *
 *   Run after changing Travel Hub content:
 *     node scripts/sync-travel-hub.mjs            # rebuild the hub, then sync
 *     node scripts/sync-travel-hub.mjs --no-build # sync an existing out/ only
 *
 *   Hub location (override if you moved it):
 *     RIDEYEAH_HUB_DIR="C:/path/to/RideYeah Travel Hub" node scripts/sync-travel-hub.mjs
 *
 * After running, commit the updated travel-static/ and deploy as usual — one
 * Cloudflare Pages deploy then serves both the main site and /travel.
 */
import {
  rmSync,
  mkdirSync,
  readdirSync,
  copyFileSync,
  statSync,
  existsSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { execSync } from "node:child_process";

const DEFAULT_HUB_DIR =
  "C:/Users/reyna/OneDrive/Desktop/Rideyeah/RideYeah Travel Hub";
const HUB_DIR = process.env.RIDEYEAH_HUB_DIR || DEFAULT_HUB_DIR;
const OUT_DIR = join(HUB_DIR, "out");
const DEST = "travel-static";
const skipBuild = process.argv.includes("--no-build");

if (!existsSync(HUB_DIR)) {
  console.error(
    `✗ Travel Hub not found at:\n    ${HUB_DIR}\n` +
      `  Set RIDEYEAH_HUB_DIR to its location and re-run.`,
  );
  process.exit(1);
}

if (!skipBuild) {
  console.log(`▶ Building the Travel Hub (output: export)…\n    ${HUB_DIR}`);
  execSync("npm run build", { cwd: HUB_DIR, stdio: "inherit", shell: true });
}

if (!existsSync(OUT_DIR)) {
  console.error(
    `✗ No out/ in the hub (${OUT_DIR}). Run without --no-build, or build the hub first.`,
  );
  process.exit(1);
}

// Recursively copy out/ -> travel-static/.
const copyDir = (from, to) => {
  mkdirSync(to, { recursive: true });
  for (const entry of readdirSync(from)) {
    const s = join(from, entry);
    const d = join(to, entry);
    if (statSync(s).isDirectory()) copyDir(s, d);
    else copyFileSync(s, d);
  }
};

let files = 0;
const count = (dir) => {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) count(p);
    else files++;
  }
};

console.log(`▶ Syncing ${OUT_DIR} → ${DEST}/`);
rmSync(DEST, { recursive: true, force: true });
copyDir(OUT_DIR, DEST);
count(DEST);

// A README so the folder's purpose is obvious in the repo.
writeFileSync(
  join(DEST, "README.txt"),
  "Generated by scripts/sync-travel-hub.mjs — do not edit by hand.\n" +
    "This is the RideYeah Travel Hub static export (rideyeah.com/travel).\n" +
    "scripts/build.mjs copies it to dist/travel/ at build time.\n",
  "utf8",
);

console.log(`✓ Synced ${files} files into ${DEST}/`);
console.log("  Next: commit travel-static/ and deploy (one Cloudflare build serves /travel).");
